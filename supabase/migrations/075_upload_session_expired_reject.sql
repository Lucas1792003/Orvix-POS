--   the call does NOT complete - it raises 'Upload link has expired' - but
--   the branch first runs `UPDATE ... SET status = 'EXPIRED'` and then
--   RAISEs, which rolls the UPDATE back: the session stays PENDING (with a
--   live signed_upload_token) and the message differs from every other
--   inactive-session path ('Upload link is no longer active', used by the
--   status <> 'PENDING' branch here and by attach_..._token). t12 records
--   the pre-075 state (status PENDING after the rejected call).
--
-- WHAT IT DOES
--   CREATE OR REPLACE with the production body byte-for-byte except ONE
--   hunk (generated; the generator asserts the diff is exactly this hunk):
--     - IF v_session.expires_at <= now() THEN
--     -   UPDATE ... SET status = 'EXPIRED', signed_upload_token = NULL ...;
--     -   RAISE EXCEPTION 'Upload link has expired';
--     + IF v_session.expires_at <= now() THEN
--     +   -- comment
--     +   RAISE EXCEPTION 'Upload link is no longer active';
--   The UPDATE is removed rather than kept because it can never persist
--   (any RAISE aborts the caller's transaction - PostgREST runs each RPC in
--   its own transaction). Expiry is therefore DERIVED, as it already is
--   everywhere else: every function treats `status = 'PENDING' AND
--   expires_at <= now()` as expired; get_product_image_upload_session_status
--   (the desktop's poll) and _by_token (the phone page's first call) stamp
--   and persist EXPIRED + clear signed_upload_token in a non-raising
