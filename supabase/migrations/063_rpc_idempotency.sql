  -- Now the product itself. product_barcodes and price_tiers
  -- cascade-delete via their own FKs.
  DELETE FROM products WHERE id = p_product_id;

  v_idem_result := jsonb_build_object('productId', p_product_id);
  PERFORM public.idem_finish(p_idempotency_key, v_idem_result);
  RETURN v_idem_result;
END;
