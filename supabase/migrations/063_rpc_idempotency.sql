--
-- Design: docs/selfhost-migration/phase-d/idempotency-contract.md.
-- Defect: docs/selfhost-migration/02-production-dependencies.md §8 row
-- "Idempotency" and change A1 - a commit-then-lost-response retry (online
-- path or outbox replay) re-executed complete_sale/adjust_stock/
-- record_supplier_payment and duplicated the sale, the stock deduction or the
-- payment; state-guarded RPCs (open/close_shift, receive, dispatch, approve...)
-- rejected the retry with an error the client cannot tell apart from a real
-- rejection.
--
-- What this does, per in-scope function (bodies are the CURRENT production
-- bodies from the 2026-10-11 schema snapshot, byte-for-byte, plus ONLY the
-- additions below - generated by a script whose self-check asserts the diff is
-- purely additive except the final RETURN line):
--   1. DROP FUNCTION of the OLD signature (explicit, so PostgREST never sees
--      two overloads of the same name).
--   2. CREATE OR REPLACE with a trailing `p_idempotency_key uuid DEFAULT NULL`.
--      NULL raises IDEMPOTENCY_KEY_REQUIRED (contract: the key is required;
--      there are no clients to keep compatible - the frontend sends a UUID v4
--      minted when the operation is created).
--   3. After the authentication block: v_idem_hash := md5(jsonb_build_object(
--      <every business argument except p_created_at and the key>)::text);
--      v_idem_replay := idem_begin(key, '<fn>', hash); replay -> RETURN it.
--   4. The original RETURN value is captured into v_idem_result,
--      idem_finish(key, v_idem_result) stores it, then it is returned.
