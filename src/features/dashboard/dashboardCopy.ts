export type DashboardCopyKey = keyof typeof en;

export const useDashboardCopy = () => {
  const { language, isZawgyi } = useLanguageStore();
  return (key: DashboardCopyKey): string => {
    const text = language === "my" ? my[key] : en[key];
    return language === "my" && isZawgyi ? unicodeToZawgyi(text) : text;
  };
};

